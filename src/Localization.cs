 static readonly KeyValuePair<string,string>[] forward=pairs.OrderByDescending(x=>x.Key.Length).ToArray(),reverse=pairs.OrderByDescending(x=>x.Value.Length).ToArray();
 static readonly ConcurrentDictionary<string,string> cache=new ConcurrentDictionary<string,string>();
 public static string T(string text){if(Language=="ru"||text==null)return text;return cache.GetOrAdd(text,s=>{foreach(var p in forward)s=s.Replace(p.Key,p.Value);return s;});}
 public static string ToLanguage(string text){if(Language!="ru")return T(text);if(text==null)return text;foreach(var p in reverse)text=text.Replace(p.Value,p.Key);return text;}
 public static void Apply(Control c){if(!(c is TextBox)&&!(c is ComboBox)){string translated=ToLanguage(c.Text);if(c.Text!=translated)c.Text=translated;}foreach(Control child in c.Controls)Apply(child);}
